import { randomUUID } from "node:crypto";
import { prisma } from "../../config/prisma";
const db = prisma as any;

const severityRank: Record<string, number> = { LOW: 1, MEDIUM: 2, HIGH: 3, CRITICAL: 4 };

export const createFraudAlert = async (input: {
  dedupeKey: string; source: "PHASE32_RULE" | "MONITORING_RULE" | "BEHAVIORAL_ANALYTICS" | "STATISTICAL_ANOMALY" | "ML_MODEL" | "MANUAL_REVIEW";
  severity: "LOW" | "MEDIUM" | "HIGH" | "CRITICAL"; title: string; description: string;
  monitoringEventId?: string; transactionId?: string; accountId?: string; userId?: string;
  riskScore?: number; evidence?: Record<string, unknown>;
}) => db.$transaction(async (tx: any) => {
  const existing = await tx.fraudAlert.findUnique({ where: { dedupeKey: input.dedupeKey } });
  if (existing) return existing;
  const alert = await tx.fraudAlert.create({ data: { ...input, evidence: input.evidence ?? {} } });
  await tx.fraudAlertAudit.create({ data: { fraudAlertId: alert.id, action: "ALERT_CREATED", toStatus: "OPEN", comment: "Alert generated by monitoring pipeline." } });
  return alert;
});

export const createCaseFromAlert = async (alertId: string, actorId?: string) => {
  const alert = await db.fraudAlert.findUnique({ where: { id: alertId } });
  if (!alert) throw new Error("Fraud alert not found");
  const existing = await db.fraudCaseAlert.findFirst({ where: { fraudAlertId: alertId }, include: { fraudCase: true } });
  if (existing) return existing.fraudCase;
  const caseRecord = await db.$transaction(async (tx: any) => {
    const record = await tx.fraudCase.create({
      data: { caseNumber: `FC-${new Date().toISOString().slice(0,10).replace(/-/g,"")}-${randomUUID().slice(0,8).toUpperCase()}`, title: alert.title, description: alert.description, priority: alert.severity, createdById: actorId },
    });
    await tx.fraudCaseAlert.create({ data: { fraudCaseId: record.id, fraudAlertId: alertId, linkedById: actorId } });
    await tx.fraudCaseAudit.create({ data: { fraudCaseId: record.id, actorId, action: "CASE_CREATED_FROM_ALERT", toStatus: "OPEN", comment: "Case created from fraud alert." } });
    return record;
  });
  return caseRecord;
};

export const transitionFraudAlert = async (alertId: string, status: string, actorId: string, comment?: string) => {
  const allowed = ["ACKNOWLEDGED", "INVESTIGATING", "RESOLVED", "ESCALATED", "FALSE_POSITIVE"];
  if (!allowed.includes(status)) throw new Error("Unsupported fraud alert status");
  return db.$transaction(async (tx: any) => {
    const current = await tx.fraudAlert.findUnique({ where: { id: alertId } });
    if (!current) throw new Error("Fraud alert not found");
    const updated = await tx.fraudAlert.update({ where: { id: alertId }, data: { status, ...(status === "ACKNOWLEDGED" ? { acknowledgedAt: new Date() } : {}), ...(status === "RESOLVED" || status === "FALSE_POSITIVE" ? { resolvedAt: new Date() } : {}), ...(status === "ESCALATED" ? { escalatedAt: new Date() } : {}) } });
    await tx.fraudAlertAudit.create({ data: { fraudAlertId: alertId, actorId, action: "STATUS_CHANGED", fromStatus: current.status, toStatus: status, comment } });
    return updated;
  });
};

export const addFraudCaseNote = async (caseId: string, authorId: string, body: string, isInternal = true) => {
  if (!body.trim()) throw new Error("Note body is required");
  return db.$transaction(async (tx: any) => {
    const note = await tx.fraudCaseNote.create({ data: { fraudCaseId: caseId, authorId, body: body.trim(), isInternal } });
    await tx.fraudCaseAudit.create({ data: { fraudCaseId: caseId, actorId: authorId, action: "NOTE_ADDED", comment: isInternal ? "Internal case note added." : "Customer-visible case note added.", metadata: { noteId: note.id, isInternal } } });
    return note;
  });
};

export const assignFraudCase = async (caseId: string, assignedToId: string, assignedById: string, reason?: string) =>
  db.$transaction(async (tx: any) => {
    const record = await tx.fraudCase.findUnique({ where: { id: caseId } });
    if (!record) throw new Error("Fraud case not found");
    await tx.fraudCaseAssignment.updateMany({ where: { fraudCaseId: caseId, unassignedAt: null }, data: { unassignedAt: new Date() } });
    const assignment = await tx.fraudCaseAssignment.create({ data: { fraudCaseId: caseId, assignedToId, assignedById, reason } });
    await tx.fraudCase.update({ where: { id: caseId }, data: { assignedAnalystId: assignedToId } });
    await tx.fraudCaseAudit.create({ data: { fraudCaseId: caseId, actorId: assignedById, action: "CASE_ASSIGNED", comment: reason, metadata: { assignedToId } } });
    return assignment;
  });

export const transitionFraudCase = async (caseId: string, status: string, actorId: string, comment?: string, resolution?: string) => {
  const statuses = ["ACKNOWLEDGED","INVESTIGATING","PENDING_INFORMATION","ESCALATED","RESOLVED","CLOSED"];
  if (!statuses.includes(status)) throw new Error("Unsupported fraud case status");
  return db.$transaction(async (tx: any) => {
    const current = await tx.fraudCase.findUnique({ where: { id: caseId } });
    if (!current) throw new Error("Fraud case not found");
    const updated = await tx.fraudCase.update({ where: { id: caseId }, data: { status, ...(status === "RESOLVED" || status === "CLOSED" ? { closedAt: new Date() } : {}), ...(resolution ? { resolution } : {}), ...(comment ? { resolutionSummary: comment } : {}) } });
    await tx.fraudCaseAudit.create({ data: { fraudCaseId: caseId, actorId, action: "STATUS_CHANGED", fromStatus: current.status, toStatus: status, comment } });
    return updated;
  });
};


/** Stores a reference to evidence already placed in approved private storage.
 * This API deliberately does not accept arbitrary local filesystem paths. */
export const addFraudCaseEvidence = async (input: {
  caseId: string; uploadedById: string; evidenceType: "DOCUMENT" | "IMAGE" | "TRANSACTION_REFERENCE" | "SYSTEM_LOG" | "EXTERNAL_REFERENCE" | "OTHER";
  storageRef: string; fileName?: string; mimeType?: string; checksum?: string; description?: string;
}) => {
  if (!input.storageRef.trim() || input.storageRef.includes("..")) throw new Error("A valid private-storage reference is required");
  const caseRecord = await db.fraudCase.findUnique({ where: { id: input.caseId }, select: { id: true } });
  if (!caseRecord) throw new Error("Fraud case not found");
  return db.$transaction(async (tx: any) => {
    const evidence = await tx.fraudCaseEvidence.create({ data: input });
    await tx.fraudCaseAudit.create({ data: { fraudCaseId: input.caseId, actorId: input.uploadedById, action: "EVIDENCE_ADDED", metadata: { evidenceId: evidence.id, evidenceType: input.evidenceType } } });
    return evidence;
  });
};
